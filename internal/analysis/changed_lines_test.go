func changedLinesRepository(t *testing.T) (string, func(...string)) {
	t.Helper()
	dir := t.TempDir()

	var err error

	dir, err = filepath.EvalSymlinks(dir)
	if err != nil {
		t.Fatal(err)
	}

	git := newTestGitRunner(t, dir)
	git("init", "-b", "main")
	git("config", "user.email", "test@example.com")
	git("config", "user.name", "Test")

	return dir, git
}

func TestGetChangedLines(t *testing.T) {
	dir, git := changedLinesRepository(t)
	commitFiles(t, dir, git, map[string]string{
		"edit.go":   "package example\n\nvar A = 1\nvar B = 2\nvar C = 3\nvar D = 4\nvar E = 5\n",
		"delete.go": "package example\n\nvar A = 1\n",
		"gone.go":   "package example\n",
		"old.go":    "package example\n\nvar Old = 1\n",
	})
	git("checkout", "-b", "feature")
	git("rm", "gone.go")
	git("mv", "old.go", "renamed.go")
	commitFiles(t, dir, git, map[string]string{
		"edit.go":           "package example\n\nvar A = 10\nvar B = 2\nvar C = 3\nvar D = 4\nvar E = 50\n",
		"delete.go":         "package example\n\n",
		"space name.go":     "package example\n\nvar New = 1\n",
		"line\nname.go":     "package example\n",
		"literal[1].go":     "package example\n",
		"ignored.go":        "package example\n",
		"vendor/lib.go":     "package example\n",
		"testdata/input.go": "package example\n",
		"example_test.go":   "package example\n",
		"generated.go":      "// Code generated by test. DO NOT EDIT.\npackage example\n",
		".gitattributes":    "attribute.go -diff\n",
		"attribute.go":      "package example\nvar Attribute = 1\n",
	})
	g := NewGitIntegration(dir)

	parser := ignore.New()
	if err := parser.LoadFromReader(strings.NewReader("ignored.go\n")); err != nil {
		t.Fatal(err)
	}

	g.SetIgnoreParser(parser)

	got, err := g.GetChangedLines("main")
	if err != nil {
		t.Fatal(err)
	}

	want := map[string][]LineRange{
		filepath.Join(dir, "edit.go"):       {{Start: 3, End: 3}, {Start: 7, End: 7}},
		filepath.Join(dir, "renamed.go"):    {{Start: 1, End: 3}},
		filepath.Join(dir, "space name.go"): {{Start: 1, End: 3}},
		filepath.Join(dir, "line\nname.go"): {{Start: 1, End: 1}},
		filepath.Join(dir, "literal[1].go"): {{Start: 1, End: 1}},
		filepath.Join(dir, "attribute.go"):  {{Start: 1, End: 2}},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("ranges = %#v, want %#v", got, want)
	}

	g.SetIncludeGenerated(true)

	got, err = g.GetChangedLines("main")
	if err != nil {
		t.Fatal(err)
	}

	if len(got[filepath.Join(dir, "generated.go")]) == 0 {
		t.Error("include-generated did not include generated.go")
	}
}

func TestGetChangedLinesTargetAndWorktree(t *testing.T) {
	dir, git := changedLinesRepository(t)
	commitFiles(t, dir, git, map[string]string{"root.go": "package example\n"})
	git("checkout", "-b", "feature")
	commitFiles(t, dir, git, map[string]string{
		"root.go":         "package example\nvar Root = 1\n",
		"sub/file.go":     "package sub\nvar Sub = 1\n",
		"sibling/file.go": "package sibling\n",
	})
	worktree := filepath.Join(t.TempDir(), "checkout")
	git("worktree", "add", "--detach", worktree, "HEAD")

	worktree, err := filepath.EvalSymlinks(worktree)
	if err != nil {
		t.Fatal(err)
	}

	for _, root := range []string{dir, worktree} {
		for _, target := range []string{filepath.Join(root, "sub"), filepath.Join(root, "sub", "file.go")} {
			t.Run(target, func(t *testing.T) {
				got, err := NewGitIntegration(target).GetChangedLines("main")
				if err != nil {
					t.Fatal(err)
				}

				want := map[string][]LineRange{filepath.Join(root, "sub", "file.go"): {{Start: 1, End: 2}}}
				if !reflect.DeepEqual(got, want) {
					t.Errorf("ranges = %#v, want %#v", got, want)
				}
			})
		}
	}
}

func TestGetChangedLinesDirtyFiles(t *testing.T) {
	for _, staged := range []bool{false, true} {
		t.Run(map[bool]string{false: "unstaged", true: "staged"}[staged], func(t *testing.T) {
			dir, git := changedLinesRepository(t)
			commitFiles(t, dir, git, map[string]string{"file.go": "package example\n"})
			git("checkout", "-b", "feature")
			commitFiles(t, dir, git, map[string]string{"file.go": "package example\nvar A = 1\n"})

			if err := os.WriteFile(filepath.Join(dir, "unrelated.txt"), []byte("local"), 0600); err != nil {
				t.Fatal(err)
			}

			g := NewGitIntegration(dir)
			if _, err := g.GetChangedLines("main"); err != nil {
				t.Fatalf("unrelated change rejected: %v", err)
			}

			if err := os.WriteFile(filepath.Join(dir, "file.go"), []byte("package example\nvar A = 2\n"), 0600); err != nil {
				t.Fatal(err)
			}

			if staged {
				git("add", "file.go")
			}

			if _, err := g.GetChangedLines("main"); err == nil || !strings.Contains(err.Error(), "file.go") {
				t.Errorf("dirty file error = %v", err)
			}
		})
	}
}

func TestGetChangedLinesErrorsAndEmpty(t *testing.T) {
	if _, err := NewGitIntegration(t.TempDir()).GetChangedLines("main"); err == nil {
		t.Error("non-repository should fail")
	}

	dir, git := changedLinesRepository(t)
	commitFiles(t, dir, git, map[string]string{"file.go": "package example\n"})

	g := NewGitIntegration(dir)
	if _, err := g.GetChangedLines("missing-ref"); err == nil || !strings.Contains(err.Error(), "missing-ref") {
		t.Errorf("missing ref error = %v", err)
	}

	got, err := g.GetChangedLines("")
	if err != nil || len(got) != 0 {
		t.Errorf("empty selection = %v, %v", got, err)
	}

	t.Run("missing git", func(t *testing.T) {
		t.Setenv("PATH", t.TempDir())

		if _, err := g.GetChangedLines("main"); err == nil || !strings.Contains(err.Error(), "git on PATH") {
			t.Errorf("missing git error = %v", err)
		}
	})
	git("checkout", "--orphan", "unrelated")
	git("commit", "-m", "unrelated root")

	if _, err := g.GetChangedLines("main"); err == nil || !strings.Contains(err.Error(), "merge base") {
		t.Errorf("missing merge base error = %v", err)
	}
}
