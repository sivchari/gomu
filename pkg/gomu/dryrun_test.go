func TestWriteDryRunFile(t *testing.T) {
	tests := []struct {
		name    string
		file    string
		mutants []mutation.Mutant
	}{
		{
			name: "two_mutants",
			file: "foo.go",
			mutants: []mutation.Mutant{
				{Line: 12, Column: 7, Mutator: "arithmetic", Type: "arithmetic_binary", Description: "Replace + with -"},
				{Line: 20, Column: 3, Mutator: "conditional", Type: "conditional_binary", Description: "Replace < with <="},
			},
		},
		{
			name:    "empty",
			file:    "foo.go",
			mutants: nil,
		},
		{
			// Mixes short and long Mutator names so tabwriter padding is locked.
			name: "alignment",
			file: "bar.go",
			mutants: []mutation.Mutant{
				{Line: 3, Column: 1, Mutator: "op", Type: "op_binary", Description: "short"},
				{Line: 120, Column: 45, Mutator: "arithmetic_binary_assignment_removal", Type: "arithmetic_assign", Description: "a much longer description to test column padding"},
				{Line: 7, Column: 2, Mutator: "logical", Type: "logical_binary", Description: "mid length description"},
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var buf bytes.Buffer

			if err := writeDryRunFile(&buf, tt.file, tt.mutants, nil); err != nil {
				t.Fatalf("writeDryRunFile: %v", err)
			}

			assertGolden(t, filepath.Join("testdata", "dryrun", tt.name+".golden"), buf.Bytes())
		})
	}
}

func TestDryRunNoFiles(t *testing.T) {
	engine, err := NewEngine(nil)
	if err != nil {
		t.Fatalf("NewEngine: %v", err)
	}

	t.Run("incremental", func(t *testing.T) {
		var buf bytes.Buffer

		opts := &RunOptions{Incremental: true, BaseBranch: "main"}
		if err := engine.dryRun(&buf, nil, opts, nil); err != nil {
			t.Fatalf("dryRun: %v", err)
		}

		out := buf.String()
		for _, want := range []string{"no files to analyze", "main", "--incremental=false"} {
			if !strings.Contains(out, want) {
				t.Errorf("output missing %q: %q", want, out)
			}
		}
	})

	t.Run("non-incremental", func(t *testing.T) {
		var buf bytes.Buffer

		opts := &RunOptions{Incremental: false}
		if err := engine.dryRun(&buf, nil, opts, nil); err != nil {
			t.Fatalf("dryRun: %v", err)
		}

		out := buf.String()
		if !strings.Contains(out, "no files to analyze") {
			t.Errorf("unexpected output for empty file list: %q", out)
		}

		for _, unwanted := range []string{"main", "--incremental=false"} {
			if strings.Contains(out, unwanted) {
				t.Errorf("output should not contain %q: %q", unwanted, out)
			}
		}
	})
}

// TestRunDryRunSkipsExecution proves the dry-run path stops before execution and
// reporting: with JSON output configured, a real run would write
// mutation-report.json, but a dry run must not.
func TestRunDryRunSkipsExecution(t *testing.T) {
	tempDir := t.TempDir()
	writeFile(t, filepath.Join(tempDir, "go.mod"), testModuleContent)
	writeFile(t, filepath.Join(tempDir, "math.go"), `package main

func Add(a, b int) int {
	return a + b
}
`)

	// Reports and history are written relative to the working directory; run
	// inside the isolated temp dir so any side effects are contained and
	// observable.
	origWD, err := os.Getwd()
	if err != nil {
		t.Fatalf("getwd: %v", err)
	}

	if err := os.Chdir(tempDir); err != nil {
		t.Fatalf("chdir: %v", err)
	}

	defer func() {
		if err := os.Chdir(origWD); err != nil {
			t.Fatalf("restore wd: %v", err)
		}
	}()

	opts := &RunOptions{DryRun: true, Incremental: false, Output: "json", Workers: 1, Timeout: 5}

	engine, err := NewEngine(opts)
	if err != nil {
		t.Fatalf("NewEngine: %v", err)
	}

	if err := engine.Run(context.Background(), ".", opts); err != nil {
		t.Fatalf("Run: %v", err)
	}

	for _, name := range []string{"mutation-report.json", ".gomu_history.json"} {
		if _, err := os.Stat(filepath.Join(tempDir, name)); !os.IsNotExist(err) {
			t.Errorf("dry run should not create %s", name)
		}
	}
}

// TestRunDryRunSkipsGeneratedFiles proves that generated Go files are
// excluded from mutation targets by default across the full run path
// (discovery + dry-run reporting), and become eligible again with
// IncludeGenerated set.
func TestRunDryRunSkipsGeneratedFiles(t *testing.T) {
	tempDir := t.TempDir()
	writeFile(t, filepath.Join(tempDir, "go.mod"), testModuleContent)
	writeFile(t, filepath.Join(tempDir, "math.go"), `package main

func Add(a, b int) int {
	return a + b
}
`)
	writeFile(t, filepath.Join(tempDir, "client.go"), `// Code generated by example-generator. DO NOT EDIT.

package main

func Sub(a, b int) int {
	return a - b
}
`)

	tests := []struct {
		name             string
		includeGenerated bool
		wantClient       bool
	}{
		{name: "excludes generated file by default", includeGenerated: false, wantClient: false},
		{name: "includes generated file with IncludeGenerated", includeGenerated: true, wantClient: true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			opts := &RunOptions{DryRun: true, Incremental: false, IncludeGenerated: tt.includeGenerated}

			engine, err := NewEngine(opts)
			if err != nil {
				t.Fatalf("NewEngine: %v", err)
			}

			out := captureStdout(t, func() {
				if err := engine.Run(context.Background(), tempDir, opts); err != nil {
					t.Fatalf("Run: %v", err)
				}
			})

			if !strings.Contains(out, "math.go") {
				t.Errorf("expected math.go in output, got: %q", out)
			}

			if strings.Contains(out, "client.go") != tt.wantClient {
				t.Errorf("client.go presence = %v, want %v; output: %q", strings.Contains(out, "client.go"), tt.wantClient, out)
			}

			if !strings.Contains(out, "Total:") {
				t.Errorf("expected dry-run summary line, got: %q", out)
			}

			if !strings.Contains(out, "arithmetic") {
				t.Errorf("expected arithmetic mutator name in output, got: %q", out)
			}

			// The mutator name matches `gomu run --list`; the finer-grained Type does not appear.
			if strings.Contains(out, "arithmetic_binary") {
				t.Errorf("output should show the mutator name, not the mutant type: %q", out)
			}
		})
	}
}

// TestRunDryRunHonorsBuildTags proves the forwarded -tags decide which
// production files are mutation targets in a dry run, and that test-selection
// flags do not.
func TestRunDryRunHonorsBuildTags(t *testing.T) {
	tests := []struct {
		name     string
		testArgs []string
		want     string
		unwanted string
	}{
		{name: "tag selects active.go", testArgs: []string{"-tags=unit"}, want: "/active.go (", unwanted: "/inactive.go ("},
		{name: "no tag selects inactive.go", testArgs: nil, want: "/inactive.go (", unwanted: "/active.go ("},
		{name: "test selection keeps production code", testArgs: []string{"-run", "^TestValue$", "-count=1"}, want: "/inactive.go (", unwanted: "/active.go ("},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			dir := t.TempDir()
			if err := os.CopyFS(dir, os.DirFS(filepath.Join("..", "..", "internal", "analysis", "testdata", "buildtags"))); err != nil {
				t.Fatalf("copy fixture: %v", err)
			}

			opts := &RunOptions{DryRun: true, Incremental: false, TestArgs: tt.testArgs}

			engine, err := NewEngine(opts)
			if err != nil {
				t.Fatalf("NewEngine: %v", err)
			}

			out := captureStdout(t, func() {
				if err := engine.Run(context.Background(), dir, opts); err != nil {
					t.Fatalf("Run: %v", err)
				}
			})

			if !strings.Contains(out, tt.want) {
				t.Errorf("expected %q as a target, got: %q", tt.want, out)
			}

			if strings.Contains(out, tt.unwanted) {
				t.Errorf("did not expect %q as a target, got: %q", tt.unwanted, out)
			}

			if !strings.Contains(out, "across 1 file(s)") {
				t.Errorf("expected exactly one target file, got: %q", out)
			}
		})
	}
}

// captureStdout redirects os.Stdout for the duration of fn and returns what
// was written to it.
func captureStdout(t *testing.T, fn func()) string {
	t.Helper()

	r, w, err := os.Pipe()
	if err != nil {
		t.Fatalf("create pipe: %v", err)
	}

	orig := os.Stdout
	os.Stdout = w

	fn()

	if err := w.Close(); err != nil {
		t.Fatalf("close pipe writer: %v", err)
	}

	os.Stdout = orig

	out, err := io.ReadAll(r)
	if err != nil {
		t.Fatalf("read captured stdout: %v", err)
	}

	return string(out)
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()

	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

// TestDryRunSeesPackageTestChange proves dry run and a normal run select the
// same files, because both go through performIncrementalAnalysis: a change to a
// test file whose name does not match the production file makes the unchanged
// production file eligible again.
func TestDryRunSeesPackageTestChange(t *testing.T) {
	tempDir := t.TempDir()
	value := filepath.Join(tempDir, "value.go")
	contract := filepath.Join(tempDir, "contract_test.go")

	writeFile(t, value, "package example\n\nfunc Value() int { return 1 }\n")
	writeFile(t, contract, "package example_test\n")

	store, err := history.New(filepath.Join(tempDir, "history.json"))
	if err != nil {
		t.Fatalf("history.New: %v", err)
	}

	hasher := analysis.NewFileHasher()

	fileHash, err := hasher.HashFile(value)
	if err != nil {
		t.Fatalf("HashFile: %v", err)
	}

	store.UpdateFileWithHashes(value, nil, nil, fileHash, hasher.HashRelatedTests(value))

	mutator, err := mutation.New()
	if err != nil {
		t.Fatalf("mutation.New: %v", err)
	}

	engine := &Engine{history: store, mutator: mutator}

	for _, dryRun := range []bool{false, true} {
		opts := &RunOptions{DryRun: dryRun, Incremental: true}

		_, files, err := engine.performIncrementalAnalysis(tempDir, opts, nil)
		if err != nil {
			t.Fatalf("performIncrementalAnalysis(dryRun=%v): %v", dryRun, err)
		}

		if len(files) != 0 {
			t.Errorf("dryRun=%v: unchanged package should be skipped, got %v", dryRun, files)
		}
	}

	writeFile(t, contract, "package example_test\n\n// stronger assertions\n")

	for _, dryRun := range []bool{false, true} {
		opts := &RunOptions{DryRun: dryRun, Incremental: true}

		_, files, err := engine.performIncrementalAnalysis(tempDir, opts, nil)
		if err != nil {
			t.Fatalf("performIncrementalAnalysis(dryRun=%v): %v", dryRun, err)
		}

		if len(files) != 1 || files[0] != value {
			t.Errorf("dryRun=%v: want [%s] after contract_test.go changed, got %v", dryRun, value, files)
		}
	}
}
